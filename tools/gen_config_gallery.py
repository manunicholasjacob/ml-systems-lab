"""Generate docs/configs.md, the example-config gallery, from configs/ itself.

The gallery is generated rather than written so it cannot drift: every entry's
description is the config's own header comment, and every count (devices, models,
runs) comes from loading the file through mlsyslab.config.load, the same expansion
`mlsys run` uses. tests/test_config_gallery.py fails when the committed page differs
from what this script would write, so adding or editing a config without regenerating
the page is caught in CI.

    python tools/gen_config_gallery.py           # rewrite docs/configs.md
    python tools/gen_config_gallery.py --check   # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import glob
import os
import sys
from typing import Dict, List, Tuple

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "docs", "configs.md")
BLOB = "https://github.com/manunicholasjacob/ml-systems-lab/blob/main/"
TREE = "https://github.com/manunicholasjacob/ml-systems-lab/tree/main/"

# Configs whose records ship in results/, so a reader can check the output without
# running anything. Keyed by path relative to the repository root.
DATASETS: Dict[str, str] = {
    "configs/pi-overnight.yaml": "results/pi5-campaign",
    "configs/laptop-overnight.yaml": "results/laptop-campaign",
    "configs/containerization.yaml": "results/containerization",
    "configs/cluster.yaml": "results/cluster",
}

# Status lines that are true of a config but not visible from its first paragraph.
NOTES: Dict[str, str] = {}

HEADER = """\
# Example configs

<!-- Generated by tools/gen_config_gallery.py from the files in configs/. Do not edit
     by hand: change the config's header comment and regenerate. -->

Every sweep is one YAML file: the machines (`devices`), the model files (`models`),
and a `matrix` that expands into concrete runs. Preview any of them without running
anything:

```
mlsys run <config> --dry-run
```

**Templates** are written to be copied. Each has `# <-- EDIT` markers on the lines
that name your paths, and a header that says what to run before and after.

**Studies** are the exact configs behind the shipped datasets and write-ups, kept so a
result can be traced to the sweep that produced it. Their paths point at the author's
machines; use them as worked examples, or edit the device and model blocks to repeat
a study on your own hardware.

The counts below come from expanding each file with the same loader `mlsys run` uses.
"""


def _paragraphs(path: str) -> List[List[str]]:
    """The config's leading comment block, split into paragraphs of raw lines."""
    paragraphs: List[List[str]] = [[]]
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            if not line.startswith("#"):
                break
            text = line[1:]
            text = text[1:] if text.startswith(" ") else text
            if not text.strip():
                if paragraphs[-1]:
                    paragraphs.append([])
                continue
            paragraphs[-1].append(text)
    return [p for p in paragraphs if p]


def _prose(paragraph: List[str]) -> str:
    """Join a paragraph into one line, dropping a final sentence that introduces a list
    or a command (it ends in a colon, and what it introduces is not in the gallery)."""
    text = " ".join(line.strip() for line in paragraph)
    if text.endswith(":"):
        cut = text.rfind(". ", 0, len(text) - 1)
        text = text[:cut + 1] if cut != -1 else text
    return text


def _description(path: str) -> str:
    """The first comment paragraph, plus the second when it is prose.

    A second paragraph that is a numbered usage list, a command or an indented table
    reads badly when joined into one line, so it is left in the file for the reader.
    """
    paragraphs = _paragraphs(path)
    if not paragraphs:
        return ""
    out = [_prose(paragraphs[0])]
    if len(paragraphs) > 1:
        second = paragraphs[1]
        procedural = second[0].split()[0].rstrip(":") in {"Usage", "Before", "Run", "Report"}
        indented = any(line.startswith(" ") for line in second)
        if not procedural and not indented:
            out.append(_prose(second))
    return "\n\n".join(out)


def _device_kind(spec: dict) -> str:
    if spec.get("kind"):
        return str(spec["kind"])
    return "ssh" if spec.get("host") else "local"


def _summary(path: str) -> Tuple[str, str, str, str, int]:
    from mlsyslab.config import load

    config = load(path)
    devices = ", ".join(f"`{d}` ({_device_kind(s)})" for d, s in config.devices.items())
    backends = ", ".join(sorted({s.backend for s in config.specs}))
    modes = ", ".join(sorted({s.mode for s in config.specs}))
    return config.experiment, devices, backends, modes, len(config.specs)


def _entry(rel: str) -> str:
    path = os.path.join(REPO, rel)
    experiment, devices, backends, modes, runs = _summary(path)
    name = os.path.basename(rel)
    out = [f"### {name}", "", _description(path), ""]
    if rel in NOTES:
        out += [f"*{NOTES[rel]}*", ""]
    out += [
        "| | |",
        "|---|---|",
        f"| file | [`{rel}`]({BLOB}{rel}) |",
        f"| experiment | `{experiment}` |",
        f"| devices | {devices} |",
        f"| backend / mode | {backends} / {modes} |",
        f"| runs | {runs} |",
    ]
    if rel in DATASETS:
        out.append(f"| shipped records | [`{DATASETS[rel]}/`]({TREE}{DATASETS[rel]}) |")
    out += ["", "```", f"mlsys run {rel} --dry-run", "```", ""]
    return "\n".join(out)


def _configs() -> Tuple[List[str], List[str]]:
    def rel(p: str) -> str:
        return os.path.relpath(p, REPO).replace(os.sep, "/")

    examples = sorted(rel(p) for p in glob.glob(os.path.join(REPO, "configs", "examples", "*.yaml")))
    top = sorted(rel(p) for p in glob.glob(os.path.join(REPO, "configs", "*.yaml")))
    templates = ["configs/example-smoke.yaml"] + examples
    studies = [p for p in top if p not in templates]
    return templates, studies


def render() -> str:
    templates, studies = _configs()
    parts = [HEADER, "## Templates", ""]
    parts += [_entry(p) for p in templates]
    parts += ["## Studies", ""]
    parts += [_entry(p) for p in studies]
    parts += [
        "## Adding one",
        "",
        "A config that answers a question other people ask is welcome as a pull request.",
        "Put a template in `configs/examples/`, open it with a header comment whose first",
        "paragraph says what question it answers, mark every machine-specific line with",
        "`# <-- EDIT`, and run `python tools/gen_config_gallery.py` to add it here.",
        "",
    ]
    return "\n".join(parts).rstrip("\n") + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if docs/configs.md is out of date, write nothing")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        try:
            with open(OUT, encoding="utf-8") as fh:
                current = fh.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print("docs/configs.md is out of date: run python tools/gen_config_gallery.py",
                  file=sys.stderr)
            return 1
        print("docs/configs.md is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
